/**
 * Writes src/countries/es-municipalities-data.ts from the INE's official list of
 * municipalities ("Relación de municipios y sus códigos por provincias"), the
 * Excel file published once a year:
 *
 *   https://www.ine.es/daco/daco42/codmun/26codmun.xlsx   (1 January 2026)
 *
 *   node packages/fairguest/scripts/es-municipalities.mjs <path to NNcodmun.xlsx> <year>
 *
 * Download the file by hand: this script never goes to the network. It reads
 * the workbook with a small zip reader (no dependency): one sheet per
 * province, a row with the province's name, then CPRO, CMUN, DC, NOMBRE.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { inflateRawSync } from "node:zlib";

const [file, year] = process.argv.slice(2);
if (!file || !/^\d{4}$/.test(year ?? "")) {
  console.error("usage: node es-municipalities.mjs <NNcodmun.xlsx> <year>");
  process.exit(2);
}

/** The files of a zip, by name (central directory, stored or deflated). */
function unzip(buf) {
  let end = buf.length - 22;
  while (end >= 0 && buf.readUInt32LE(end) !== 0x06054b50) end--;
  if (end < 0) throw new Error("not a zip file");
  const count = buf.readUInt16LE(end + 10);
  let at = buf.readUInt32LE(end + 16);
  const files = new Map();
  for (let i = 0; i < count; i++) {
    const method = buf.readUInt16LE(at + 10);
    const size = buf.readUInt32LE(at + 20);
    const nameLen = buf.readUInt16LE(at + 28);
    const extraLen = buf.readUInt16LE(at + 30);
    const commentLen = buf.readUInt16LE(at + 32);
    const local = buf.readUInt32LE(at + 42);
    const name = buf.toString("utf8", at + 46, at + 46 + nameLen);
    const start = local + 30 + buf.readUInt16LE(local + 26) + buf.readUInt16LE(local + 28);
    const raw = buf.subarray(start, start + size);
    files.set(name, method === 0 ? raw : inflateRawSync(raw));
    at += 46 + nameLen + extraLen + commentLen;
  }
  return files;
}

const xmlText = (s) => s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, "&");
const files = unzip(readFileSync(file));
const shared = [...files.get("xl/sharedStrings.xml").toString("utf8").matchAll(/<si>([\s\S]*?)<\/si>/g)].map((m) =>
  xmlText([...m[1].matchAll(/<t[^>]*>([\s\S]*?)<\/t>/g)].map((t) => t[1]).join("")),
);

const provinces = new Map();
const rows = [];
for (const [name, data] of files) {
  if (!/^xl\/worksheets\/sheet\d+\.xml$/.test(name)) continue;
  let province = null;
  for (const row of data.toString("utf8").matchAll(/<row[^>]*>([\s\S]*?)<\/row>/g)) {
    const cells = [...row[1].matchAll(/<c([^>]*?)(?:\/>|>([\s\S]*?)<\/c>)/g)].map((c) => {
      const v = /<v>([\s\S]*?)<\/v>/.exec(c[2] ?? "")?.[1];
      if (v === undefined) return "";
      return /t="s"/.test(c[1]) ? shared[Number(v)] : xmlText(v);
    });
    if (cells.length === 1 && cells[0] && !cells[0].startsWith("Relaci")) province = cells[0].trim();
    else if (cells.length >= 4 && /^\d{2}$/.test(cells[0]) && /^\d{3}$/.test(cells[1]) && /^\d$/.test(cells[2])) {
      if (!provinces.has(cells[0])) provinces.set(cells[0], province);
      rows.push(`${cells[0]}${cells[1]}${cells[2]}${cells[3].trim()}`);
    }
  }
}
rows.sort();
if (provinces.size !== 52 || rows.length < 8000) throw new Error(`unexpected file: ${provinces.size} provinces, ${rows.length} municipalities`);

const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/countries/es-municipalities-data.ts");
const provinceLines = [...provinces].sort(([a], [b]) => a.localeCompare(b)).map(([code, name]) => `  "${code}": ${JSON.stringify(name)},`);
writeFileSync(
  out,
  `/**
 * Spain's municipalities and their INE codes, as of 1 January ${year}.
 * Source: INE, «Relación de municipios y sus códigos por provincias»
 * (https://www.ine.es/daco/daco42/codmun/${year.slice(2)}codmun.xlsx).
 * Generated by scripts/es-municipalities.mjs: do not edit by hand.
 */

export const ES_MUNICIPALITIES_YEAR = ${year};

/** Province code (CPRO) → the INE's name of the province. */
export const ES_PROVINCES: Readonly<Record<string, string>> = {
${provinceLines.join("\n")}
};

/** One municipality per line: CPRO (2) + CMUN (3) + DC (1), then the INE's name. */
export const ES_MUNICIPALITIES_RAW = ${JSON.stringify(rows.join("\n"))};
`,
);
console.log(`Wrote ${out}: ${rows.length} municipalities, ${provinces.size} provinces.`);
